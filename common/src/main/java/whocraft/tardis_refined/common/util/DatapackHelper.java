public class DatapackHelper {

    public static Logger LOGGER = LogManager.getLogger("TardisRefined/DatapackHelper");


    public static boolean writeDesktopToFile(ServerLevel level, BlockPos bottomCorner, BlockPos topCorner, boolean includeEntities, Identifier structure, DesktopTheme desktop, String datapackName) {
        MinecraftServerStorageAccessor accessor = (MinecraftServerStorageAccessor) level.getServer();
        Path rootDir = accessor.getStorageSource().getLevelPath(LevelResource.DATAPACK_DIR).normalize();
        Path datapackRoot = rootDir.resolve(datapackName);
        Path datapackDataFolder = datapackRoot.resolve("data");
        String fileExtension = ".json";
        JsonObject currentDesktop = DesktopTheme.getCodec().encodeStart(JsonOps.INSTANCE, desktop)
                .getOrThrow().getAsJsonObject();
        Path output = createAndValidatePathToDatapackObject(datapackDataFolder, desktop.getIdentifier(), TardisDesktops.getReloadListener(), fileExtension);
        createPackDefinition(datapackRoot);
        if (createStructure(level, bottomCorner, topCorner, includeEntities, structure, datapackDataFolder)) {
            if (saveJsonToPath(currentDesktop, output))
                return true;
        }
        return false;
    }

    public static boolean saveJsonToPath(JsonElement jsonElement, Path path) {
        try {
            Files.createDirectories(path.getParent());
            try (BufferedWriter writer = Files.newBufferedWriter(path)) {
                writer.write(TardisRefined.GSON.toJson(jsonElement));
            }
            return true;
        } catch (IOException e) {
            LOGGER.error(e.getMessage().toString());
            return false;
        }
    }

    public static void createPackDefinition(Path packRoot) {
        Path metaFile = packRoot.resolve("pack.mcmeta");
        if (!Files.exists(metaFile)) {
            JsonObject pack = new JsonObject();
            pack.addProperty("pack_format", SharedConstants.DATA_PACK_FORMAT_MAJOR);
            pack.addProperty("description", "Datapack generated by the Tardis Refined mod");

            JsonObject root = new JsonObject();
            root.add("pack", pack);

            try {
                Files.createDirectories(packRoot);
                try (BufferedWriter writer = Files.newBufferedWriter(metaFile)) {
                    writer.write(TardisRefined.GSON.toJson(root));
                }
            } catch (IOException e) {
                LOGGER.error(e.getMessage().toString());
            }
        }
    }

    public static boolean createStructure(ServerLevel level, BlockPos bottomCorner, BlockPos topCorner, boolean includeEntities, Identifier structure, Path packRoot) {
        StructureTemplateManager structureTemplateManager = level.getStructureTemplateManager();

        StructureTemplate structureTemplate;
        try {
            structureTemplate = structureTemplateManager.getOrCreate(structure);
        } catch (IdentifierException e) {
            LOGGER.error(e.getMessage().toString());
            return false;
        }

        AABB boundingBox = AABB.encapsulatingFullBlocks(bottomCorner, topCorner);

        ////===Size Calculation Start===
        // This mimics using the Structure Block's Detect Size feature with CORNER mode, where the start and end corners need to be placed one block diagonally outside the structure area.

        //Add two to account for the corner blocks so we get the right size dimensions. If we didn't the size will be oversize by one on all sides, when we call StructureTemplate#fillFromWorld
        int xSize = (int) boundingBox.getXsize() + 2;
        int ySize = (int) boundingBox.getYsize() + 2;
        int zSize = (int) boundingBox.getZsize() + 2;
        Vec3i structureSize = new Vec3i(xSize, ySize, zSize).north().west().below(); //1.19.3+ - use joml maths version


        //Add one to each dimension to move the bottom corner position one block inwards, diagonally and upwards.
        BlockPos pasteStartPos = BlockPos.containing(boundingBox.minX, boundingBox.minY, boundingBox.minZ);

        //===Size Calculation End===

        structureTemplate.fillFromWorld(level, pasteStartPos, structureSize, includeEntities, java.util.List.of(Blocks.STRUCTURE_VOID));
        structureTemplate.setAuthor("");

        Path path = createAndValidatePathToDatapackObject(packRoot, structure, "structures", ".nbt");
        Path pathParent = path.getParent();
        if (pathParent == null) {
            return false;
        } else {
            try {
                Files.createDirectories(Files.exists(pathParent, new LinkOption[0]) ? pathParent.toRealPath() : pathParent);
            } catch (IOException var13) {
                LOGGER.error("Failed to create parent directory: {}", pathParent);
                return false;
            }

            CompoundTag compoundTag = structureTemplate.save(new CompoundTag());

            try {
                OutputStream outputStream = new FileOutputStream(path.toFile());

                try {
                    NbtIo.writeCompressed(compoundTag, outputStream);
                } catch (Throwable throwable) { //Catch nbt write errors
                    try {
                        outputStream.close();
                    } catch (Throwable throwable1) { //Catch output stream close errors
                        throwable.addSuppressed(throwable1);
                    }

                    throw throwable;
                }

                outputStream.close();
                return true;
            } catch (Throwable throwable) {
                return false;
            }
        }

    }

    private static Path createAndValidatePathToDatapackObject(Path path, Identifier resourceLocation, CodecJsonReloadListener<?> listener, String fileExtension) {
        return createAndValidatePathToDatapackObject(path, resourceLocation, listener.getFolderName(), fileExtension);
    }

    private static Path createAndValidatePathToDatapackObject(Path path, Identifier resourceLocation, String folderName, String fileExtension) {
        Path root = path.toAbsolutePath().normalize();
        Path candidate = createPathToResult(root, resourceLocation, folderName, fileExtension).toAbsolutePath().normalize();
        if (candidate.startsWith(root) && !candidate.equals(root)) {
            return candidate;
        }
        throw new IdentifierException("Invalid resource path: " + candidate);
    }

    public static Path createPathToResult(Path path, Identifier resourceLocation, String folderName, String fileExtension) {
        try {
            Path result = resolveValidatedSegments(path, resourceLocation.getNamespace());
            result = resolveValidatedSegments(result, folderName);
            String[] resourceSegments = resourceLocation.getPath().split("/", -1);
            for (int i = 0; i < resourceSegments.length - 1; i++) {
                result = resolveValidatedSegments(result, resourceSegments[i]);
            }
            String fileName = resourceSegments[resourceSegments.length - 1] + fileExtension;
            validatePortableSegment(fileName);
            return result.resolve(fileName).normalize();
        } catch (InvalidPathException e) {
            throw new IdentifierException("Invalid resource path: " + resourceLocation, e);
        }
    }

    private static Path resolveValidatedSegments(Path root, String value) {
        Path result = root;
        for (String segment : value.split("/", -1)) {
            validatePortableSegment(segment);
            result = result.resolve(segment);
        }
        return result;
    }

    private static void validatePortableSegment(String segment) {
        if (segment.isEmpty() || segment.equals(".") || segment.equals("..")
                || segment.endsWith(".") || segment.endsWith(" ")) {
            throw new InvalidPathException(segment, "Non-portable or unsafe path segment");
        }
        for (int i = 0; i < segment.length(); i++) {
            char c = segment.charAt(i);
            if (c < 32 || "<>:\\\"|?*".indexOf(c) >= 0) {
                throw new InvalidPathException(segment, "Non-portable or unsafe path segment");
            }
        }
        String deviceName = segment.split("\\.", 2)[0].toUpperCase(java.util.Locale.ROOT);
        if (deviceName.equals("CON") || deviceName.equals("PRN") || deviceName.equals("AUX")
                || deviceName.equals("NUL") || deviceName.matches("COM[1-9]") || deviceName.matches("LPT[1-9]")) {
            throw new InvalidPathException(segment, "Non-portable or unsafe path segment");
        }
    }
}
